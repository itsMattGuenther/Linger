// Tauri's Rust crates and JavaScript packages on the same version (#788):
// read from both lockfiles in every shape they take, and a mismatch, or
// anything unreadable, fails.
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { CARGO_LOCK, CARGO_TOML, PNPM_LOCK, cargoPackages, patches, pnpmDependencies, problems, unusedPatches } from "./tauri-versions.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const SCRIPT = fileURLToPath(new URL("./tauri-versions.mjs", import.meta.url));

/** A Cargo.lock holding these packages, as Cargo writes one. */
const cargoLock = (packages) => `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4
${packages.map(([name, version]) => `
[[package]]
name = "${name}"
version = "${version}"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "0000"
dependencies = [
 "serde",
]
`).join("")}`;

/** A pnpm-lock.yaml whose client has these dependencies and dev dependencies. */
const pnpmLock = (dependencies, devDependencies = []) => {
  const block = (title, entries) => entries.length ? `    ${title}:\n${entries.map(([name, version, quote = "'"]) =>
    `      ${quote}${name}${quote}:\n        specifier: ^${version.replace(/\(.*/, "")}\n        version: ${version}\n`).join("")}` : "";
  return `lockfileVersion: '9.0'

settings:
  autoInstallPeers: true
  excludeLinksFromLockfile: false

importers:

  .:
${block("dependencies", dependencies)}${block("devDependencies", devDependencies)}
packages:

  '@tauri-apps/api@2.12.4':
    resolution: {integrity: sha512-x}
`;
};

const today = {
  cargo: [["tauri", "2.11.5"], ["tauri-build", "2.6.3"], ["tauri-plugin", "2.6.3"], ["tauri-plugin-deep-link", "2.4.10"],
    ["tauri-plugin-notification", "2.3.3"], ["tauri-plugin-opener", "2.5.4"], ["tauri-plugin-updater", "2.10.1"]],
  pnpm: [["@tauri-apps/api", "2.11.1"], ["@tauri-apps/plugin-notification", "2.3.3"], ["@tauri-apps/plugin-opener", "2.5.4"]],
  dev: [["@tauri-apps/cli", "2.11.4"]],
};
const check = ({ cargo = today.cargo, pnpm = today.pnpm, dev = today.dev } = {}) =>
  problems(cargoPackages(cargoLock(cargo)), pnpmDependencies(pnpmLock(pnpm, dev)));
const swap = (list, name, version) => list.map(([n, v, ...rest]) => [n, n === name ? version : v, ...rest]);

test("the lockfiles are read in every shape they take", () => {
  const cargo = cargoPackages(cargoLock([["tauri", "2.12.5"], ["windows", "0.61.3"], ["windows", "0.62.2"]]));
  assert.deepEqual(cargo.get("tauri"), ["2.12.5"]);
  assert.deepEqual(cargo.get("windows"), ["0.61.3", "0.62.2"]);
  const pnpm = pnpmDependencies(pnpmLock(
    [["@tauri-apps/api", "2.12.4(react@19.2.0)"], ["react", "19.2.0", ""], ["@tauri-apps/plugin-opener", "2.7.2", '"']],
    [["@tauri-apps/cli", "2.12.4"]]));
  assert.deepEqual([...pnpm], [["@tauri-apps/api", "2.12.4"], ["react", "19.2.0"], ["@tauri-apps/plugin-opener", "2.7.2"], ["@tauri-apps/cli", "2.12.4"]]);
});

test("the importer's sections that hold no versions are read past, and only those", () => {
  const lock = pnpmLock(today.pnpm, today.dev).replace("\npackages:", `    dependenciesMeta:
      linger-core:
        injected: true
    publishDirectory: dist

packages:`);
  assert.deepEqual([...pnpmDependencies(lock).keys()], ["@tauri-apps/api", "@tauri-apps/plugin-notification", "@tauri-apps/plugin-opener", "@tauri-apps/cli"]);
});

test("the repository's own lockfiles match", () => {
  const cargo = cargoPackages(readFileSync(join(ROOT, CARGO_LOCK), "utf8"));
  const pnpm = pnpmDependencies(readFileSync(join(ROOT, PNPM_LOCK), "utf8"));
  assert.deepEqual(problems(cargo, pnpm), []);
  assert(pnpm.has("@tauri-apps/api") && pnpm.has("@tauri-apps/cli") && cargo.has("tauri"));
});

test("today's versions match, and so does a whole move to 2.12", () => {
  assert.deepEqual(check(), []);
  assert.deepEqual(check({
    cargo: [["tauri", "2.12.5"], ["tauri-plugin-notification", "2.8.0"], ["tauri-plugin-opener", "2.7.2"], ["tauri-plugin-updater", "2.14.1"]],
    pnpm: [["@tauri-apps/api", "2.12.4"], ["@tauri-apps/plugin-notification", "2.8.0"], ["@tauri-apps/plugin-opener", "2.7.2"]],
    dev: [["@tauri-apps/cli", "2.12.4"]],
  }), []);
});

test("a half-moved upgrade fails, naming what doesn't match", () => {
  const cases = [
    [{ cargo: swap(today.cargo, "tauri", "2.12.5") }, [/@tauri-apps\/api is 2\.11\.1 and the tauri crate is 2\.12\.5/, /@tauri-apps\/cli is 2\.11\.4/]],
    [{ pnpm: swap(today.pnpm, "@tauri-apps/api", "2.12.4") }, [/@tauri-apps\/api is 2\.12\.4 and the tauri crate is 2\.11\.5/]],
    [{ dev: swap(today.dev, "@tauri-apps/cli", "2.12.4") }, [/@tauri-apps\/cli is 2\.12\.4/]],
    [{ cargo: swap(today.cargo, "tauri-plugin-opener", "2.7.2") }, [/@tauri-apps\/plugin-opener is 2\.5\.4 and the tauri-plugin-opener crate is 2\.7\.2/]],
    [{ pnpm: swap(today.pnpm, "@tauri-apps/plugin-notification", "3.3.0") }, [/plugin-notification is 3\.3\.0/]],
    [{ pnpm: [...today.pnpm, ["@tauri-apps/plugin-clipboard-manager", "2.3.0"]] }, [/has no tauri-plugin-clipboard-manager/]],
    [{ cargo: [...today.cargo, ["tauri", "2.12.5"]] }, [/2 versions of tauri \(2\.11\.5, 2\.12\.5\)/]],
    [{ cargo: today.cargo.filter(([name]) => name !== "tauri") }, [/has no tauri; it needs one/]],
    [{ pnpm: today.pnpm.filter(([name]) => name !== "@tauri-apps/api") }, [/has no @tauri-apps\/api/]],
    [{ dev: [] }, [/has no @tauri-apps\/cli/]],
    [{ pnpm: swap(today.pnpm, "@tauri-apps/api", "link:../api") }, [/can't read @tauri-apps\/api's version, link:\.\.\/api/]],
  ];
  for (const [change, expected] of cases) {
    const found = check(change);
    assert.equal(found.length, expected.length, `${JSON.stringify(change)}: ${found.join("; ")}`);
    expected.forEach((pattern, i) => assert.match(found[i], pattern));
  }
});

test("a Rust-only plugin, with no package of its own, needs nothing to match", () => {
  assert.deepEqual(check({ cargo: swap(today.cargo, "tauri-plugin-updater", "2.14.1") }), []);
});

test("what it can't read fails, naming it, rather than being passed over", () => {
  const lock = pnpmLock(today.pnpm, today.dev);
  const cases = [
    () => cargoPackages("version = 4\n"),
    () => cargoPackages(`version = 4\n\n[[package]]\nname = "tauri"\nsource = "x"\n`),
    () => pnpmDependencies(lock.replace("lockfileVersion: '9.0'", "lockfileVersion: '6.0'")),
    () => pnpmDependencies(lock.replace("importers:", "importer:")),
    () => pnpmDependencies(lock.replace("\n  .:\n", "\n  client:\n")),
    () => pnpmDependencies(lock.replace("        version: 2.11.1\n", "        version: 2.11.1\n        resolution: x\n")),
    () => pnpmDependencies(lock.replace("      '@tauri-apps/api':\n", "      - '@tauri-apps/api':\n")),
    // #841's review: a section it doesn't know, and an entry with no version,
    // dropped every package in them and passed.
    () => pnpmDependencies(lock.replace("    dependencies:\n", "    dependenciez:\n")),
    () => pnpmDependencies(lock.replace("        version: 2.11.1\n", "")),
    () => pnpmDependencies(lock.replace("  .:\n", "  .:\n      '@tauri-apps/api':\n")),
  ];
  const errors = [/no \[\[package\]\]/, /without a name and a version/, /lockfile version 6\.0/, /no importers/, /no "\." importer/,
    /:\d+: can't read "resolution: x"/, /:\d+: can't read "- '@tauri-apps\/api':"/,
    /:\d+: the "\." importer has "dependenciez:", which this doesn't know/, /:\d+: @tauri-apps\/api has no version/,
    /:\d+: can't read "'@tauri-apps\/api':"/];
  cases.forEach((read, i) => assert.throws(read, errors[i], String(read)));
});

test("run: in a repository whose lockfiles don't match, it fails and says what", (t) => {
  const dir = mkdtempSync(join(tmpdir(), "tauri-versions-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  execFileSync("git", ["init", "-q"], { cwd: dir });
  const write = (path, text) => { mkdirSync(dirname(join(dir, path)), { recursive: true }); writeFileSync(join(dir, path), text); };
  write(CARGO_TOML, "[package]\nname = \"linger-client\"\n");
  write(CARGO_LOCK, cargoLock(swap(today.cargo, "tauri", "2.12.5")));
  write(PNPM_LOCK, pnpmLock(today.pnpm, today.dev));
  const failed = spawnSync("node", [SCRIPT], { cwd: join(dir, "client"), encoding: "utf8" });
  assert.equal(failed.status, 1, failed.stdout);
  assert.match(failed.stderr, /@tauri-apps\/api is 2\.11\.1 and the tauri crate is 2\.12\.5/);
  write(CARGO_LOCK, cargoLock(today.cargo));
  const passed = spawnSync("node", [SCRIPT], { cwd: dir, encoding: "utf8" });
  assert.equal(passed.status, 0, passed.stderr);
  assert.match(passed.stdout, /^Tauri's crates and packages match: tauri 2\.11\.5, @tauri-apps\/api 2\.11\.1, @tauri-apps\/cli 2\.11\.4\.\n$/);
});

// The Windows installers are built on Tauri's own templates: main.wxs is a
// copy of one, and installer-hooks.nsh hooks into the other at named places.
// Each says which Tauri CLI it was checked against, and after an upgrade this
// fails until somebody has compared it with the new CLI's template. Tauri
// 2.12's NSIS template changed (Restart Manager), and only the Windows package
// check on GitHub noticed (#836).
test("the Windows installer files name the Tauri CLI they were checked against", () => {
  const cli = pnpmDependencies(readFileSync(join(ROOT, PNPM_LOCK), "utf8")).get("@tauri-apps/cli");
  for (const [path, pattern] of [
    ["client/src-tauri/windows/main.wxs", /Based on Tauri CLI v(\d+\.\d+\.\d+)/],
    ["client/src-tauri/windows/installer-hooks.nsh", /Hooks into Tauri CLI v(\d+\.\d+\.\d+)'s NSIS installer template/],
  ]) {
    const named = pattern.exec(readFileSync(join(ROOT, path), "utf8"))?.[1];
    assert.equal(named, cli,
      `${path} was checked against Tauri CLI ${named}, and the CLI is ${cli}: compare it with that CLI's template, then change the version it names`);
  }
});

// A pin (#836): Cargo.toml takes tao from Linger's own copy until tao releases
// tauri-apps/tao#1376. Cargo drops a pin that stops fitting with only a warning,
// so the lockfile must show the pin in use, and every pin names what it waits for.
const REV = "10e79e36ab73ac7f631b5c97783d99130414073d";
const pinned = `[package]
name = "linger-client"

[dependencies]
tauri = "2.12.5"

# Why it's pinned.
# upstream: tauri-apps/tao#1376
[patch.crates-io]
tao = { git = "https://github.com/itsMattGuenther/tao", rev = "${REV}" }
`;
const lockWith = (source) => `version = 4

[[package]]
name = "tao"
version = "0.37.2"
${source ? `source = "${source}"\n` : ""}
[[package]]
name = "tauri"
version = "2.12.5"
source = "registry+https://github.com/rust-lang/crates.io-index"
`;

test("a pin is read with what it waits for, and nothing else is", () => {
  assert.deepEqual(patches(pinned), [{ name: "tao", git: "https://github.com/itsMattGuenther/tao", rev: REV, upstream: "tauri-apps/tao#1376" }]);
  assert.deepEqual(patches("[package]\nname = \"x\"\n\n[dependencies]\ntao = { git = \"https://x\", rev = \"1\" }\n"), []);
  assert.throws(() => patches(pinned.replace("[patch.crates-io]", "[profile.release]\nlto = true\n\n[patch.crates-io]")),
    /names no "# upstream/, "an upstream line above another section isn't the pin's");
});

test("[patch.crates-io] is read however TOML writes it, and any other patch form fails", () => {
  const want = patches(pinned);
  for (const header of ['[patch."crates-io"]', "[patch.'crates-io']", "[ patch . crates-io ]", "[patch.crates-io] # until tao releases it"]) {
    assert.deepEqual(patches(pinned.replace("[patch.crates-io]", header)), want, header);
  }
  // Each of these is a patch Cargo would build from, in a form this doesn't
  // read: it fails rather than seeing no pins (#850's review).
  for (const text of [
    pinned.replace("[patch.crates-io]\ntao = {", "[patch.crates-io.tao]\nx = {"),
    pinned.replace("[patch.crates-io]\ntao = {", "[patch]\ncrates-io.tao = {"),
    pinned.replace("[patch.crates-io]", '[patch."https://github.com/tauri-apps/tao"]'),
    pinned.replace("[patch.crates-io]", "[[patch.crates-io]]"),
    pinned.replace("[patch.crates-io]\ntao = {", "patch.crates-io.tao = {"),
    `[package]\nname = "x"\n${'"patch"'}.crates-io.tao = { git = "https://x", rev = "${REV}" }\n`,
  ]) assert.throws(() => patches(text), /pins are read from \[patch\.crates-io\] only/, text);
});

test("a pin it can't read, or one that names nothing to wait for, fails", () => {
  const cases = [
    [pinned.replace("# upstream: tauri-apps/tao#1376\n", ""), /names no "# upstream: owner\/repo#N"/],
    [pinned.replace("tauri-apps/tao#1376", "the tao fix"), /an upstream is owner\/repo#number/],
    [pinned.replace(`rev = "${REV}"`, 'branch = "linger"'), /a pin is name = \{ git = "https:\/\/\.\.\.", rev = "<the whole commit>" \}/],
    [pinned.replace(REV, REV.slice(0, 8)), /a pin is name/],
    [pinned.replace(/tao = \{.*\}/, 'tao = { path = "../tao" }'), /a pin is name/],
    [pinned.replace(/tao = \{.*\}/, 'tao = "0.37.3"'), /a pin is name/],
  ];
  for (const [text, error] of cases) assert.throws(() => patches(text), error, text);
});

test("a pin the lockfile doesn't build from is named, so its fix can't go quietly", () => {
  const pins = patches(pinned);
  assert.deepEqual(unusedPatches(pins, lockWith(`git+https://github.com/itsMattGuenther/tao?rev=${REV}#${REV}`)), []);
  for (const lock of [
    lockWith("registry+https://github.com/rust-lang/crates.io-index"),
    lockWith(`git+https://github.com/itsMattGuenther/tao?rev=${"0".repeat(40)}#${"0".repeat(40)}`),
    lockWith(`git+https://github.com/someone/tao?rev=${REV}#${REV}`),
    lockWith(null).replace(/\[\[package\]\]\nname = "tao"[\s\S]*?\n\n/, ""),
    lockWith(`git+https://github.com/itsMattGuenther/tao?rev=${REV}#${REV}`) + '\n[[package]]\nname = "tao"\nversion = "0.37.3"\nsource = "registry+x"\n',
  ]) assert.match(unusedPatches(pins, lock).join(""), /doesn't build tao from the pin/, lock);
});

test("the repository's own pins are each in use", () => {
  const pins = patches(readFileSync(join(ROOT, CARGO_TOML), "utf8"));
  assert.deepEqual(unusedPatches(pins, readFileSync(join(ROOT, CARGO_LOCK), "utf8")), []);
});
